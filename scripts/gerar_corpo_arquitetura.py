def make_table(header, rows, ratios, caption=None, align_center_cols=None):
    """Tabela padrão: cabeçalho HEADER_FILL, zebra TABLE_STRIPE, células em Paragraph."""
    assert abs(sum(ratios) - 1.0) < 0.001, 'ratios devem somar 1.0'
    col_widths = [r * AVAIL_W * 0.98 for r in ratios]
    assert sum(col_widths) <= AVAIL_W + 0.5
    align_center_cols = align_center_cols or []
    data = [[Paragraph(f'<b>{c}</b>', S['th']) for c in header]]
    for r in rows:
        line = []
        for i, c in enumerate(r):
            st = S['td_c'] if i in align_center_cols else S['td']
            line.append(Paragraph(c, st))
        data.append(line)
    t = Table(data, colWidths=col_widths, hAlign='CENTER', repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('LEFTPADDING', (0, 0), (-1, -1), 7), ('RIGHTPADDING', (0, 0), (-1, -1), 7),
        ('TOPPADDING', (0, 0), (-1, -1), 5.5), ('BOTTOMPADDING', (0, 0), (-1, -1), 5.5),
    ]
    for i in range(1, len(data)):
        style.append(('BACKGROUND', (0, i), (-1, i),
                      TABLE_ROW_ODD if i % 2 == 1 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    story.append(Spacer(1, 14))
    if caption:
        story.append(KeepTogether([t, Spacer(1, 6), Paragraph(caption, S['caption'])]))
    else:
        story.append(t)
    story.append(Spacer(1, 14))

def embed_image(path, max_width, max_height):
    pil = PILImage.open(path)
    ow, oh = pil.size
    ratio = min(max_width / ow if ow > max_width else 1.0,
                max_height / oh if oh > max_height else 1.0)
    return Image(path, width=ow * ratio, height=oh * ratio)

