def header_footer(canvas, doc):
    canvas.saveState()
    # Cabeçalho: título + régua accent
    canvas.setFont('FreeSerif', 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, PAGE_H - 0.55 * inch, DOC_TITLE)
    canvas.setStrokeColor(ACCENT)
    canvas.setLineWidth(1.2)
    canvas.line(MARGIN, PAGE_H - 0.62 * inch, PAGE_W - MARGIN, PAGE_H - 0.62 * inch)
    # Rodapé: página 1 = sumário (romano); demais = arábico a partir de 1
    canvas.setFont('FreeSerif', 9)
    canvas.setFillColor(TEXT_MUTED)
    if doc.page == 1:
        canvas.drawCentredString(PAGE_W / 2, 0.5 * inch, 'i')
    else:
        canvas.drawCentredString(PAGE_W / 2, 0.5 * inch, str(doc.page - 1))
    canvas.restoreState()

